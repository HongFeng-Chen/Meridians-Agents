#!/usr/bin/env node
/**
 * 由 api/openapi.yaml 生成前端 SDK。
 *
 * 输入：go_agent/api/openapi.yaml（由 buf + protoc-gen-openapi 从 api/**\/*.proto 生成）
 * 输出：src/api/generated/{paths.js, types.js, index.js}
 *
 * 约定：
 *   - 只导出下面 SERVICE_GROUPS 里声明的服务（模板自带的 TodoService 不导出）；
 *   - operationId 形如 `RagService_ListDocs`，拆成「分组 rag」+「方法 listDocs」；
 *   - 请求 body 只从 body schema 里挑字段，路径参数不进 body；
 *   - multipart 操作（requestBody schema 为 string）生成 FormData，文件字段固定为 file；
 *   - 所有字段名即 proto 里显式声明的 json_name（snake_case），与后端 JSON 完全一致。
 *
 * 用法：node scripts/gen-sdk.mjs      （或 npm run gen:sdk）
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const HERE = dirname(fileURLToPath(import.meta.url));
const SPEC_PATH = resolve(HERE, '../../go_agent/api/openapi.yaml');
const OUT_DIR = resolve(HERE, '../src/api/generated');

/** tag → { group: 导出命名空间, file: 说明 } */
const SERVICE_GROUPS = {
  RagService: { group: 'rag', label: 'RAG / GraphRAG' },
  PromptService: { group: 'prompt', label: '提示词工程' },
  MemoryService: { group: 'memory', label: '记忆系统' },
  LLMService: { group: 'llm', label: '大模型数据源' },
  LLMCallQueryService: { group: 'llm', label: 'LLM 调用历史' },
  SkillService: { group: 'skill', label: '技能与技能市场' },
  MCPService: { group: 'mcp', label: 'MCP 服务与工具' },
  AgentFactoryService: { group: 'agentfactory', label: 'Agent 工厂' },
  HistoryService: { group: 'history', label: '统一操作历史' },
  ConversationService: { group: 'conversation', label: '会话' },
  AIPlatformService: { group: 'aiplatform', label: 'AI 平台（千问 / 百炼）' },
  HarnessService: { group: 'harness', label: '评测 Harness' },
  AdminService: { group: 'admin', label: '系统管理（租户 / 成员）' },
  AuthService: { group: 'auth', label: '登录与身份' },
  PolicyService: { group: 'auth', label: 'Casbin 策略管理' },
};

const HTTP_METHODS = ['get', 'post', 'put', 'patch', 'delete'];

const spec = parse(readFileSync(SPEC_PATH, 'utf8'));
const schemas = spec.components?.schemas ?? {};

/** 解析 $ref，返回 { name, schema } */
function deref(node) {
  if (!node) return { name: null, schema: null };
  if (node.$ref) {
    const name = node.$ref.split('/').pop();
    return { name, schema: schemas[name] ?? null };
  }
  return { name: null, schema: node };
}

/** schema 里的类型名：去掉包前缀，重名时加分组前缀 */
const typeName = (raw) => raw?.replace(/^[a-z0-9_]+\.v1\./, '') ?? null;

function collectOperations() {
  const ops = [];
  for (const [path, item] of Object.entries(spec.paths ?? {})) {
    for (const method of HTTP_METHODS) {
      const op = item[method];
      if (!op) continue;
      const tag = op.tags?.[0] ?? '';
      const group = SERVICE_GROUPS[tag];
      if (!group) continue; // 跳过未声明的服务（如 TodoService）

      const [serviceName, rpcName] = (op.operationId ?? '').split('_');
      const name = rpcName.charAt(0).toLowerCase() + rpcName.slice(1);

      const params = op.parameters ?? [];
      const pathParams = params.filter((p) => p.in === 'path').map((p) => p.name);
      const queryParams = params.filter((p) => p.in === 'query').map((p) => p.name);

      // 两种请求体形态：
      //   multipart/form-data —— 文件上传（proto 的 bytes 字段，由 patch_openapi.py 补全契约）
      //   application/json    —— 普通 JSON 请求
      const multipartBody = op.requestBody?.content?.['multipart/form-data'];
      const jsonBody = op.requestBody?.content?.['application/json'];
      const bodyRef = deref(jsonBody?.schema);
      const multipart = Boolean(multipartBody);
      const hasBody = Boolean(jsonBody) && !multipart;
      const bodyProps = hasBody ? Object.keys(bodyRef.schema?.properties ?? {}) : [];

      const resp = deref(op.responses?.['200']?.content?.['application/json']?.schema);

      ops.push({
        key: op.operationId,
        group: group.group,
        label: group.label,
        service: tag,
        rpc: rpcName,
        name,
        method: method.toUpperCase(),
        path,
        summary: (op.description ?? op.summary ?? '').split('\n')[0].trim(),
        pathParams,
        queryParams,
        hasBody,
        multipart,
        bodyProps: bodyProps.filter((f) => !pathParams.includes(f)),
        requestType: typeName(bodyRef.name),
        responseType: typeName(resp.name),
      });
    }
  }
  return ops;
}

const operations = collectOperations();

// 跨服务重名去重：同名 rpc 加服务前缀（如 LLM 与 Conversation 都有 chat → llmChat / conversationChat）
{
  const seen = new Map();
  for (const op of operations) {
    const first = seen.get(op.name);
    if (first) {
      const rename = (o) => {
        o.name = `${o.group}${o.rpc.charAt(0).toUpperCase()}${o.rpc.slice(1)}`;
        o.renamed = true;
      };
      if (!first.renamed) rename(first);
      rename(op);
    } else {
      seen.set(op.name, op);
    }
  }
}

/* ---------------- paths.js ---------------- */

function emitPaths() {
  const lines = [
    '// Code generated by frontend/scripts/gen-sdk.mjs from go_agent/api/openapi.yaml. DO NOT EDIT.',
    '// 每个 operation 的元数据：路径、方法、参数名、是否有 body、是否 multipart。',
    '',
    'export const OPERATIONS = {',
  ];
  for (const op of operations) {
    lines.push(`  ${op.key}: {`);
    lines.push(`    service: '${op.service}',`);
    lines.push(`    group: '${op.group}',`);
    lines.push(`    method: '${op.method}',`);
    lines.push(`    path: '${op.path}',`);
    lines.push(`    summary: ${JSON.stringify(op.summary)},`);
    lines.push(`    pathParams: ${JSON.stringify(op.pathParams)},`);
    lines.push(`    queryParams: ${JSON.stringify(op.queryParams)},`);
    lines.push(`    hasBody: ${op.hasBody},`);
    lines.push(`    multipart: ${op.multipart},`);
    lines.push(`    bodyProps: ${JSON.stringify(op.bodyProps)},`);
    lines.push('  },');
  }
  lines.push('};', '');
  lines.push(`export const OPERATION_COUNT = ${operations.length};`, '');
  return lines.join('\n');
}

/* ---------------- types.js ---------------- */

function jsType(node) {
  const { name, schema } = deref(node);
  if (!schema) return 'any';
  if (name) return typeName(name);
  if (schema.type === 'array') return `${jsType(schema.items)}[]`;
  switch (schema.type) {
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'string':
      return 'string';
    case 'object':
      if (schema.additionalProperties) {
        const v = schema.additionalProperties;
        const vt = typeof v === 'object' ? jsType(v) : jsType({ type: 'string' });
        return `Object<string, ${vt}>`;
      }
      return 'Object<string, any>';
    default:
      return 'any';
  }
}

function emitTypes() {
  const lines = [
    '// Code generated by frontend/scripts/gen-sdk.mjs from go_agent/api/openapi.yaml. DO NOT EDIT.',
    '// 字段名与后端 JSON 完全一致（snake_case），改协议后请重新生成。',
    '',
  ];

  // 输出纳入契约的所有消息（含只作为嵌套字段出现的类型，如 Document / Hit / Version）
  const byPkg = new Map();
  for (const [fullName, schema] of Object.entries(schemas)) {
    const pkg = fullName.split('.').slice(0, 2).join('.'); // rag.v1 / llm.v1 ...
    const service = SERVICE_BY_PKG.get(pkg);
    if (!service) continue; // 跳过模板自带的 todo.v1
    if (!byPkg.has(service)) byPkg.set(service, []);
    byPkg.get(service).push([typeName(fullName), fullName]);
  }

  for (const [service, types] of byPkg) {
    lines.push(`/* ---------- ${SERVICE_GROUPS[service].label}（${service}） ---------- */`, '');
    for (const [shortName, fullName] of types) {
      const schema = schemas[fullName];
      const required = new Set(schema.required ?? []);
      lines.push('/**');
      lines.push(` * ${schema.description ?? shortName}`);
      lines.push(` * @typedef {Object} ${shortName}`);
      for (const [prop, propSchema] of Object.entries(schema.properties ?? {})) {
        const desc = propSchema.description ? ` ${propSchema.description.replace(/\s+/g, ' ')}` : '';
        const opt = required.has(prop) ? prop : `[${prop}]`;
        lines.push(` * @property {${jsType(propSchema)}} ${opt}${desc ? ` -${desc}` : ''}`);
      }
      lines.push(' */');
      lines.push('');
    }
  }
  return lines.join('\n');
}

/** 记录每个 service 的 proto 包名，用于拼 schema 全名 */
const OP_PKG = new Map([
  ['RagService', 'rag.v1'],
  ['PromptService', 'prompt.v1'],
  ['MemoryService', 'memory.v1'],
  ['LLMService', 'llm.v1'],
  ['SkillService', 'skill.v1'],
  ['MCPService', 'mcp.v1'],
]);

/** 反查：proto 包名 → service（用于按包遍历 schema） */
const SERVICE_BY_PKG = new Map([...OP_PKG].map(([service, pkg]) => [pkg, service]));


/* ---------------- index.js ---------------- */

function emitIndex() {
  const lines = [
    '// Code generated by frontend/scripts/gen-sdk.mjs from go_agent/api/openapi.yaml. DO NOT EDIT.',
    '//',
    '// 用法：',
    "//   import { rag, prompt } from './api/generated/index.js';",
    "//   const ans = await rag.query({ question: 'Milvus 怎么用？' });",
    '//',
    '// 每个方法签名都是 (input = {}, options = {}) => Promise<响应>,',
    '// input 同时承载路径参数、query 参数与 JSON body（按名字自动分派）。',
    '',
    "import { call } from '../http.js';",
    '',
  ];

  const groups = [...new Set(operations.map((o) => o.group))];
  for (const group of groups) {
    const ops = operations.filter((o) => o.group === group);
    const label = SERVICE_GROUPS[ops[0].service].label;
    lines.push(`/* ---------- ${label} ---------- */`, '');
    for (const op of ops) {
      const inputType = op.requestType ?? 'Object';
      const outType = op.responseType ?? 'any';
      const doc = [` * ${op.summary || op.rpc}`, ' *'];
      doc.push(` * ${op.method} ${op.path}`);
      if (op.pathParams.length) doc.push(` * @param {${inputType}} input 路径参数：${op.pathParams.join(', ')}`);
      if (op.queryParams.length) doc.push(` *   query 参数：${op.queryParams.join(', ')}`);
      if (op.multipart) doc.push(' *   multipart：file 走表单，其余字段走 query');
      else if (op.hasBody) doc.push(' *   其余字段作为 JSON body 提交');
      doc.push(` * @returns {Promise<${outType}>}`);
      lines.push('/**');
      lines.push(...doc);
      lines.push(' */');
      lines.push(`export const ${op.name} = (input = {}, options) =>`);
      lines.push(`  call('${op.key}', input, options);`);
      lines.push('');
    }
  }

  lines.push('/* ---------- 按服务聚合，便于整体引入 ---------- */', '');
  for (const group of groups) {
    const ops = operations.filter((o) => o.group === group);
    lines.push(`export const ${group} = {`);
    for (const op of ops) lines.push(`  ${op.name},`);
    lines.push('};', '');
  }
  lines.push('export { OPERATIONS } from \'./paths.js\';', '');
  lines.push("export * from './types.js';", '');
  return lines.join('\n');
}

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(resolve(OUT_DIR, 'paths.js'), emitPaths(), 'utf8');
writeFileSync(resolve(OUT_DIR, 'types.js'), emitTypes(), 'utf8');
writeFileSync(resolve(OUT_DIR, 'index.js'), emitIndex(), 'utf8');

const stat = Object.entries(
  operations.reduce((acc, op) => ((acc[op.group] = (acc[op.group] ?? 0) + 1), acc), {}),
)
  .map(([g, n]) => `${g}:${n}`)
  .join(' ');
console.log(`[gen-sdk] ${operations.length} operations → ${OUT_DIR}`);
console.log(`[gen-sdk] ${stat}`);
